def get_init_state(pattern: str = "a", position: int = 5):
    state = np.zeros((45, 45), dtype=np.int8)

    tiles = {
        1: (0, 0),
        2: (0, 15),
        3: (0, 30),

        4: (15, 0),
        5: (15, 15),
        6: (15, 30),

        7: (30, 0),
        8: (30, 15),
        9: (30, 30),
    }

    tile_row, tile_col = tiles[position]

    state[tile_row: tile_row + 15,  tile_col: tile_col + 15] = np.array(patterns.get(pattern.lower(), "peace"))

    return state


def draw_state(stdscr: curses.window, state: np.ndarray, live_cell: str = '#', dead_cell: str = '.'):
    for y, row in enumerate(state):
        for x, cell in enumerate(row):
            char = live_cell * 2 if cell else dead_cell * 2
            stdscr.addstr(y, x * 2, char)

    stdscr.refresh()
